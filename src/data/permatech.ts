function media(
  id: string,
  suggestedFilename: string,
  alt: string,
  caption: string,
  [width, height]: [number, number],
  fullWidth = false,
): ProjectImageSlot {
  return {
    id,
    suggestedFilename,
    alt,
    caption,
    brief: caption,
    aspectRatio: `${width} / ${height}`,
    recommendedDimensions: `${width} × ${height} px`,
    fullWidth,
    ...capturedMedia[id],
  };
}

